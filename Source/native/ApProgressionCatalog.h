inline const Mission* FindMission(const char* name) {
    if(name) for(const auto& m:Missions) if(std::strcmp(m.name,name)==0) return &m;
    return nullptr;
}
inline const Marker* FindMarker(uint32_t handle) {
    for(const auto& m:Markers) if(m.handle==handle) return &m;
    return nullptr;
}
inline bool CountedStory(int id) { return id>=867530200 && id<FinalStory && id!=CutsceneStory; }
inline bool SectorOpen(unsigned mask,int sector) { return sector>=0 && sector<7 && (mask & (1u<<sector)); }
inline bool MissionOpen(const Mission& m,unsigned mask,int count,int required,bool requireFinalSector=true) {
    if(m.id==FinalStory) return count>=required && (!requireFinalSector || SectorOpen(mask,m.sector));
    return SectorOpen(mask,m.sector);
}
